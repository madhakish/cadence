import Foundation
import SwiftData
import XCTest
import CadenceCore

/// Schema V16 (watch sync identity): every V15 store upgrades without touching
/// a row, keeps its sessions, and gains stable unique `syncID`s from the
/// idempotent post-open backfill.
@MainActor
final class WatchSyncIdentityTests: XCTestCase {
    private func temporaryStore() throws -> (URL, () -> Void) {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        return (directory.appendingPathComponent("Cadence.store"), { try? FileManager.default.removeItem(at: directory) })
    }

    private func isUUID(_ value: String) -> Bool { UUID(uuidString: value) != nil }

    func testActualProductionV15StoreMigratesAndGainsSyncIDs() throws {
        let environment = ProcessInfo.processInfo.environment
        guard let path = environment["CADENCE_V15_STORE_DIR"] else {
            if environment["CADENCE_REQUIRE_SHIPPED_STORES"] == "1" {
                XCTFail("The production V15 store did not reach XCTest")
                return
            }
            throw XCTSkip("The production V15 fixture is generated by macOS CI")
        }
        let source = URL(fileURLWithPath: path, isDirectory: true)
        let (url, cleanup) = try temporaryStore()
        defer { cleanup() }
        for file in try FileManager.default.contentsOfDirectory(at: source, includingPropertiesForKeys: nil) {
            try FileManager.default.copyItem(at: file, to: url.deletingLastPathComponent()
                .appendingPathComponent(file.lastPathComponent.replacingOccurrences(of: "default", with: "Cadence")))
        }
        var library: Set<String> = []
        do {
            // A read-only open proves the frozen V15 checksum matches the schema the
            // real predecessor binary wrote.
            let schema = Schema(versionedSchema: CadenceSchemaV15.self)
            let prior = try ModelContainer(for: schema, configurations:
                ModelConfiguration(schema: schema, url: url, allowsSave: false))
            library = Set(try prior.mainContext.fetch(FetchDescriptor<CadenceSchemaV15.Exercise>()).map {
                "\($0.id ?? "nil")|\($0.name)|\($0.isFavorite)"
            })
            XCTAssertFalse(library.isEmpty)
        }
        let schema = Schema(versionedSchema: CadenceSchemaV16.self)
        let upgraded = try ModelContainer(for: schema, migrationPlan: CadenceV15MigrationPlan.self,
            configurations: ModelConfiguration(schema: schema, url: url))
        XCTAssertEqual(Set(try upgraded.mainContext.fetch(FetchDescriptor<Exercise>()).map {
            "\($0.id ?? "nil")|\($0.name)|\($0.isFavorite)"
        }), library)
        try Seeder.syncLibrary(context: upgraded.mainContext)
        XCTAssertTrue(try upgraded.mainContext.fetch(FetchDescriptor<SetEntry>()).allSatisfy { isUUID($0.syncID) })
        XCTAssertTrue(try upgraded.mainContext.fetch(FetchDescriptor<SessionExercise>()).allSatisfy { isUUID($0.syncID) })
    }

    func testV15DiskStoreKeepsSessionsAndGainsUniqueStableSyncIDs() throws {
        let (url, cleanup) = try temporaryStore()
        defer { cleanup() }
        let sessionID = "b0000000-0000-4000-8000-000000000016"
        do {
            let schema = Schema(versionedSchema: CadenceSchemaV15.self)
            let old = try ModelContainer(for: schema, configurations: ModelConfiguration("sync", schema: schema, url: url))
            let session = CadenceSchemaV15.WorkoutSession(date: Date(timeIntervalSince1970: 1_800_000_000))
            session.id = sessionID
            session.notes = "Synthetic open session"
            for order in 0..<2 {
                let entry = CadenceSchemaV15.SessionExercise(order: order)
                entry.exerciseID = "synthetic-lift-\(order)"
                for setOrder in 0..<3 {
                    let set = CadenceSchemaV15.SetEntry(order: setOrder)
                    set.weightLb = 100 + Double(order * 10 + setOrder)
                    set.reps = 5
                    set.statusRaw = setOrder == 0 ? "completed" : "planned"
                    set.sessionExercise = entry
                    old.mainContext.insert(set)
                }
                entry.session = session
                old.mainContext.insert(entry)
            }
            old.mainContext.insert(session)
            try old.mainContext.save()
        }

        let schema = Schema(versionedSchema: CadenceSchemaV16.self)
        var minted: [String: String] = [:]
        do {
            let upgraded = try ModelContainer(for: schema, migrationPlan: CadenceV15MigrationPlan.self,
                configurations: ModelConfiguration("sync", schema: schema, url: url))
            let context = upgraded.mainContext
            let session = try XCTUnwrap(try context.fetch(FetchDescriptor<WorkoutSession>()).first)
            XCTAssertEqual(session.id, sessionID)
            XCTAssertEqual(session.notes, "Synthetic open session")
            XCTAssertNil(session.syncStateData)
            XCTAssertNil(session.watchHealthOutcomeRaw)
            XCTAssertNil(session.watchHealthWorkoutID)
            XCTAssertNil(session.syncReviewRaw)
            let sets = try context.fetch(FetchDescriptor<SetEntry>())
            XCTAssertEqual(sets.count, 6)
            XCTAssertTrue(sets.allSatisfy { $0.syncID.isEmpty }, "the migration itself touches no row")
            XCTAssertEqual(Set(sets.map(\.weightLb)), [100, 101, 102, 110, 111, 112])
            XCTAssertEqual(sets.filter { $0.status == .completed }.count, 2)

            try Seeder.syncLibrary(context: context)
            let entries = try context.fetch(FetchDescriptor<SessionExercise>())
            let ids = sets.map(\.syncID) + entries.map(\.syncID)
            XCTAssertTrue(ids.allSatisfy(isUUID))
            XCTAssertEqual(Set(ids).count, ids.count, "every sync ID is unique")
            for set in sets { minted["\(set.weightLb)"] = set.syncID }

            try Seeder.ensureSyncIDs(context: context)
            XCTAssertEqual(Dictionary(uniqueKeysWithValues: sets.map { ("\($0.weightLb)", $0.syncID) }), minted,
                           "the backfill is idempotent")
            try context.save()
        }
        let reopened = try ModelContainer(for: schema, migrationPlan: CadenceV15MigrationPlan.self,
            configurations: ModelConfiguration("sync", schema: schema, url: url))
        let sets = try reopened.mainContext.fetch(FetchDescriptor<SetEntry>())
        XCTAssertEqual(Dictionary(uniqueKeysWithValues: sets.map { ("\($0.weightLb)", $0.syncID) }), minted,
                       "sync IDs survive a reopen")
        XCTAssertTrue(sets.allSatisfy { $0.sessionExercise?.session?.id == sessionID })
    }

    func testBackfillRepairsDuplicateAndMalformedIDsAndKeepsValidOnes() throws {
        let schema = Schema(versionedSchema: CadenceSchemaV16.self)
        let container = try ModelContainer(for: schema,
            configurations: ModelConfiguration(schema: schema, isStoredInMemoryOnly: true))
        let context = container.mainContext
        let keep = "c0000000-0000-4000-8000-000000000016"
        let entry = SessionExercise(order: 0, exercise: nil)
        context.insert(entry)
        let a = SetEntry(order: 0, weightLb: 100, reps: 5)
        let b = SetEntry(order: 1, weightLb: 100, reps: 5)
        let c = SetEntry(order: 2, weightLb: 100, reps: 5)
        a.syncID = keep; b.syncID = keep; c.syncID = "not-a-uuid"
        for set in [a, b, c] { set.sessionExercise = entry; context.insert(set) }
        try context.save()

        try Seeder.ensureSyncIDs(context: context)
        let ids = [a, b, c].map(\.syncID)
        XCTAssertTrue(ids.allSatisfy(isUUID))
        XCTAssertEqual(Set(ids).count, 3)
        XCTAssertTrue(ids.contains(keep), "one valid holder keeps its ID")
    }

    func testNewEntriesAndSetsAreBornWithSyncIDs() {
        let entry = SessionExercise(order: 0, exercise: nil)
        let set = SetEntry(order: 0, weightLb: 135, reps: 8)
        XCTAssertTrue(isUUID(entry.syncID))
        XCTAssertTrue(isUUID(set.syncID))
        XCTAssertNotEqual(SetEntry(order: 0, weightLb: 135, reps: 8).syncID, set.syncID)
    }
}
