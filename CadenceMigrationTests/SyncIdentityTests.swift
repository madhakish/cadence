import Foundation
import SwiftData
import XCTest
import CadenceCore

/// Schema V16 (watch sync, #335): stable sync IDs on session entries and sets,
/// plus device-local sync and Health-ownership fields on the session.
@MainActor
final class SyncIdentityTests: XCTestCase {
    private func temporaryStore() throws -> (directory: URL, url: URL) {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        return (directory, directory.appendingPathComponent("Cadence.store"))
    }

    private func setFingerprint(_ set: SetEntry) -> String {
        "\(set.order)|\(set.weightLb)|\(set.reps)|\(set.statusRaw)|\(set.isWarmup)|\(set.flagsRaw)|"
            + "\(set.autoregReasonRaw ?? "-")|\(set.durationSeconds ?? -1)|\(set.plannedWeightLb ?? -1)"
    }

    func testActualProductionV15StoreMigratesWithoutChangingAnything() throws {
        let environment = ProcessInfo.processInfo.environment
        guard let path = environment["CADENCE_V15_STORE_DIR"] else {
            if environment["CADENCE_REQUIRE_SHIPPED_STORES"] == "1" {
                XCTFail("The production V15 store did not reach XCTest")
                return
            }
            throw XCTSkip("The production V15 fixture is generated by macOS CI")
        }
        let source = URL(fileURLWithPath: path, isDirectory: true)
        let (directory, _) = try temporaryStore()
        defer { try? FileManager.default.removeItem(at: directory) }
        for file in try FileManager.default.contentsOfDirectory(at: source, includingPropertiesForKeys: nil) {
            try FileManager.default.copyItem(at: file, to: directory.appendingPathComponent(file.lastPathComponent))
        }
        let url = directory.appendingPathComponent("default.store")
        XCTAssertTrue(FileManager.default.fileExists(atPath: url.path))
        var definitions: Set<String> = []
        var equipment: Set<String> = []
        do {
            // A read-only open also proves the frozen V15 checksum matches the
            // schema emitted by the real predecessor binary.
            let schema = Schema(versionedSchema: CadenceSchemaV15.self)
            let prior = try ModelContainer(for: schema, configurations:
                ModelConfiguration(schema: schema, url: url, allowsSave: false))
            definitions = Set(try prior.mainContext.fetch(FetchDescriptor<CadenceSchemaV15.Exercise>()).map {
                "\($0.id ?? "nil")|\($0.name)|\($0.isFavorite)|\($0.gateStatusRaw)|\($0.defaultRestSeconds)"
            })
            equipment = Set(try prior.mainContext.fetch(FetchDescriptor<CadenceSchemaV15.Gym>()).map {
                "\($0.id)|\($0.name)|\($0.plateThemeRaw)|\($0.collarWeightLb)"
            })
            XCTAssertFalse(definitions.isEmpty); XCTAssertFalse(equipment.isEmpty)
        }
        let schema = Schema(versionedSchema: CadenceSchemaV16.self)
        let upgraded = try ModelContainer(for: schema, migrationPlan: CadenceV15MigrationPlan.self,
            configurations: ModelConfiguration(schema: schema, url: url))
        let context = upgraded.mainContext
        XCTAssertEqual(Set(try context.fetch(FetchDescriptor<Exercise>()).map {
            "\($0.id ?? "nil")|\($0.name)|\($0.isFavorite)|\($0.gateStatusRaw)|\($0.defaultRestSeconds)"
        }), definitions)
        XCTAssertEqual(Set(try context.fetch(FetchDescriptor<Gym>()).map {
            "\($0.id)|\($0.name)|\($0.plateThemeRaw)|\($0.collarWeightLb)"
        }), equipment)
        try Seeder.syncLibrary(context: context)
        XCTAssertTrue(try context.fetch(FetchDescriptor<SetEntry>()).allSatisfy { UUID(uuidString: $0.syncID) != nil })
        XCTAssertTrue(try context.fetch(FetchDescriptor<WorkoutSession>()).allSatisfy {
            $0.syncStateData == nil && $0.watchHealthOutcomeRaw == nil && $0.syncReviewReasonRaw == nil
        })
    }

    // [INV-WATCH-SYNC-IDENTITY]
    func testV15DiskStoreGainsSyncIdentityWithoutTouchingTheLog() throws {
        let (directory, url) = try temporaryStore()
        defer { try? FileManager.default.removeItem(at: directory) }
        let sessionID = "b0000000-0000-4000-8000-000000000335"
        var before: [String] = []
        do {
            let schema = Schema(versionedSchema: CadenceSchemaV15.self)
            let old = try ModelContainer(for: schema, configurations: ModelConfiguration("sync", schema: schema, url: url))
            let context = old.mainContext
            let lift = CadenceSchemaV15.Exercise(name: "Synthetic Bench")
            context.insert(lift)
            let session = CadenceSchemaV15.WorkoutSession(date: Date(timeIntervalSince1970: 1_800_000_000))
            session.id = sessionID; session.isCompleted = true
            context.insert(session)
            for order in 0..<2 {
                let entry = CadenceSchemaV15.SessionExercise(order: order)
                entry.exercise = lift; entry.exerciseID = "a0000000-0000-4000-8000-000000000001"
                entry.session = session
                context.insert(entry)
                for setOrder in 0..<3 {
                    let set = CadenceSchemaV15.SetEntry(order: setOrder)
                    set.weightLb = 185 - Double(setOrder) * 10; set.reps = 5 + setOrder
                    set.statusRaw = setOrder == 2 ? "skipped" : "completed"
                    set.isWarmup = setOrder == 0; set.flagsRaw = setOrder == 1 ? ["grindy", "rir1"] : []
                    set.autoregReasonRaw = setOrder == 1 ? "bar speed" : nil
                    set.plannedWeightLb = 185; set.durationSeconds = order == 1 ? 45 : nil
                    set.sessionExercise = entry
                    context.insert(set)
                    before.append("\(order)/\(set.order)|\(set.weightLb)|\(set.reps)|\(set.statusRaw)|\(set.isWarmup)|"
                        + "\(set.flagsRaw)|\(set.autoregReasonRaw ?? "-")|\(set.durationSeconds ?? -1)|\(set.plannedWeightLb ?? -1)")
                }
            }
            try context.save()
        }
        let schema = Schema(versionedSchema: CadenceSchemaV16.self)
        var minted: [String: String] = [:]
        do {
            let upgraded = try ModelContainer(for: schema, migrationPlan: CadenceV15MigrationPlan.self,
                configurations: ModelConfiguration("sync", schema: schema, url: url))
            let context = upgraded.mainContext
            let session = try XCTUnwrap(try context.fetch(FetchDescriptor<WorkoutSession>()).first)
            XCTAssertEqual(session.id, sessionID); XCTAssertTrue(session.isCompleted)
            XCTAssertNil(session.syncStateData); XCTAssertNil(session.watchHealthOutcomeRaw)
            XCTAssertNil(session.watchHealthWorkoutID); XCTAssertNil(session.syncReviewReasonRaw)
            let after = session.orderedExercises.enumerated().flatMap { index, entry in
                entry.orderedSets.map { "\(index)/" + setFingerprint($0) }
            }
            XCTAssertEqual(after, before, "performed values, warmups, flags and order survive the upgrade")
            let sets = try context.fetch(FetchDescriptor<SetEntry>())
            let entries = try context.fetch(FetchDescriptor<SessionExercise>())
            XCTAssertTrue(sets.allSatisfy { $0.syncID.isEmpty } && entries.allSatisfy { $0.syncID.isEmpty },
                          "lightweight migration adds the literal default; the backfill mints IDs")

            try Seeder.syncLibrary(context: context)
            XCTAssertEqual(Set(sets.map(\.syncID)).count, sets.count)
            XCTAssertEqual(Set(entries.map(\.syncID)).count, entries.count)
            XCTAssertTrue(sets.allSatisfy { UUID(uuidString: $0.syncID) != nil })
            minted = Dictionary(uniqueKeysWithValues: sets.map { (setFingerprint($0) + "|\($0.sessionExercise?.order ?? -1)", $0.syncID) })
            try context.save()
        }
        let reopened = try ModelContainer(for: schema, migrationPlan: CadenceV15MigrationPlan.self,
            configurations: ModelConfiguration("sync", schema: schema, url: url))
        let sets = try reopened.mainContext.fetch(FetchDescriptor<SetEntry>())
        try Seeder.syncLibrary(context: reopened.mainContext)
        XCTAssertEqual(Dictionary(uniqueKeysWithValues: sets.map { (setFingerprint($0) + "|\($0.sessionExercise?.order ?? -1)", $0.syncID) }),
                       minted, "IDs persist and a second backfill changes nothing")
    }

    // [INV-WATCH-SYNC-IDENTITY]
    func testBackfillKeepsValidIDsAndRepairsDuplicates() throws {
        let schema = Schema(versionedSchema: CadenceSchemaV16.self)
        let container = try ModelContainer(for: schema,
            configurations: ModelConfiguration(schema: schema, isStoredInMemoryOnly: true))
        let context = container.mainContext
        let session = WorkoutSession()
        context.insert(session)
        let entry = SessionExercise(order: 0, exercise: nil)
        entry.session = session
        context.insert(entry)
        let sets = (0..<3).map { SetEntry(order: $0, weightLb: 100, reps: 5) }
        for set in sets { set.sessionExercise = entry; context.insert(set) }
        let kept = sets[0].syncID
        sets[1].syncID = kept
        sets[2].syncID = "not-a-uuid"
        try Seeder.ensureSyncIDs(context: context)
        XCTAssertEqual(Set(sets.map(\.syncID)).count, 3)
        XCTAssertTrue(sets.contains { $0.syncID == kept }, "one holder of a valid ID keeps it")
        XCTAssertTrue(sets.allSatisfy { UUID(uuidString: $0.syncID) != nil })
        let snapshot = sets.map(\.syncID)
        try Seeder.ensureSyncIDs(context: context)
        XCTAssertEqual(sets.map(\.syncID), snapshot)
    }

    // [INV-WATCH-SYNC-IDENTITY]
    func testNewRowsMintTheirOwnSyncIDs() {
        let a = SetEntry(order: 0, weightLb: 100, reps: 5)
        let b = SetEntry(order: 1, weightLb: 100, reps: 5)
        let entry = SessionExercise(order: 0, exercise: nil)
        XCTAssertNotNil(UUID(uuidString: a.syncID)); XCTAssertNotNil(UUID(uuidString: entry.syncID))
        XCTAssertNotEqual(a.syncID, b.syncID)
    }

    // [INV-WATCH-SYNC-IDENTITY]
    func testRestoreMintsFreshSyncIDsAndCarriesNoSyncState() throws {
        let schema = Schema(versionedSchema: CadenceSchemaV16.self)
        let source = try ModelContainer(for: schema,
            configurations: ModelConfiguration(schema: schema, isStoredInMemoryOnly: true))
        try Seeder.seedIfNeeded(context: source.mainContext)
        let session = WorkoutSession(date: Date(timeIntervalSince1970: 1_800_000_000))
        session.isCompleted = true
        session.syncStateData = Data("device-local".utf8)
        session.watchHealthOutcomeRaw = "saved"; session.watchHealthWorkoutID = "hk-synthetic"
        source.mainContext.insert(session)
        let lift = try XCTUnwrap(try source.mainContext.fetch(FetchDescriptor<Exercise>()).first)
        let entry = SessionExercise(order: 0, exercise: lift)
        entry.exerciseID = lift.id
        entry.session = session
        source.mainContext.insert(entry)
        let set = SetEntry(order: 0, weightLb: 135, reps: 8, status: .completed)
        set.sessionExercise = entry
        source.mainContext.insert(set)
        try source.mainContext.save()
        let data = try ExportService.jsonData(context: source.mainContext)

        let restored = try ModelContainer(for: schema,
            configurations: ModelConfiguration(schema: schema, isStoredInMemoryOnly: true))
        _ = try ImportService.load(data, into: restored.mainContext)
        let copies = try restored.mainContext.fetch(FetchDescriptor<SetEntry>())
        let copy = try XCTUnwrap(copies.first { $0.weightLb == 135 && $0.reps == 8 })
        XCTAssertNotNil(UUID(uuidString: copy.syncID))
        XCTAssertNotEqual(copy.syncID, set.syncID, "sync never spans a restore (design section 2)")
        let restoredSession = try XCTUnwrap(try restored.mainContext.fetch(FetchDescriptor<WorkoutSession>()).first)
        XCTAssertNil(restoredSession.syncStateData)
        XCTAssertNil(restoredSession.watchHealthOutcomeRaw)
        XCTAssertNil(restoredSession.watchHealthWorkoutID)
    }
}
