// Install rendered loaded-bar sprites into both clients and generate the
// placement manifests they read. Run after render-plate-sprites.py:
//   node web/tools/install-plate-sprites.mjs <render-dir> [<extra-render-dir> ...]
// Writes web/app/assets/plates/*.png + web/app/js/plate-sprites.js and
// Cadence/Assets.xcassets/PlateSprites/<name>.imageset + Cadence/Views/PlateSprites.swift.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../..", import.meta.url));
const dirs = process.argv.slice(2);
if (!dirs.length) throw new Error("Provide the render directory");
const manifest = { unit: null, angles: null, elevation: null, plates: {}, sprites: {} };
for (const dir of dirs) {
  const m = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8"));
  manifest.unit ??= m.unit; manifest.angles ??= m.angles; manifest.elevation ??= m.elevation;
  Object.assign(manifest.plates, m.plates);
  for (const sprite of m.sprites) manifest.sprites[sprite.file.replace(/\.png$/, "")] = { ...sprite, dir };
}
const webDir = join(root, "web/app/assets/plates");
const iosDir = join(root, "Cadence/Assets.xcassets/PlateSprites");
rmSync(webDir, { recursive: true, force: true }); mkdirSync(webDir, { recursive: true });
rmSync(iosDir, { recursive: true, force: true }); mkdirSync(iosDir, { recursive: true });
writeFileSync(join(iosDir, "Contents.json"), JSON.stringify({ info: { author: "xcode", version: 1 } }, null, 2) + "\n");
const names = Object.keys(manifest.sprites).sort();
for (const name of names) {
  const { dir, file } = manifest.sprites[name];
  copyFileSync(join(dir, file), join(webDir, file));
  const set = join(iosDir, `${name}.imageset`);
  mkdirSync(set);
  copyFileSync(join(dir, file), join(set, file));
  writeFileSync(join(set, "Contents.json"), JSON.stringify({
    images: [{ filename: file, idiom: "universal", scale: "1x" }, { idiom: "universal", scale: "2x" }, { idiom: "universal", scale: "3x" }],
    info: { author: "xcode", version: 1 }, properties: { "template-rendering-intent": "original" },
  }, null, 2) + "\n");
  delete manifest.sprites[name].dir;
}
const entries = names.map((name) => [name, manifest.sprites[name]]);
writeFileSync(join(root, "web/app/js/plate-sprites.js"),
  `// Generated by web/tools/install-plate-sprites.mjs from render-plate-sprites.py output. Do not edit.\n` +
  `export const PLATE_SPRITES = ${JSON.stringify({ unit: manifest.unit, angles: manifest.angles, elevation: manifest.elevation, plates: manifest.plates, sprites: Object.fromEntries(entries) }, null, 1)};\n`);
const swiftSprite = ([name, s]) => {
  if (s.kind) return `        "${name}": .bar(kind: "${s.kind}", angle: "${s.angle}", size: CGSize(width: ${s.size[0]}, height: ${s.size[1]}), axisStart: CGPoint(x: ${s.axisStart[0]}, y: ${s.axisStart[1]}), axisEnd: CGPoint(x: ${s.axisEnd[0]}, y: ${s.axisEnd[1]}), spanUnits: ${s.spanUnits}),`;
  return `        "${name}": .plate(family: "${s.family}", shape: "${s.shape}", angle: "${s.angle}", size: CGSize(width: ${s.size[0]}, height: ${s.size[1]}), faceCenter: CGPoint(x: ${s.faceCenter[0]}, y: ${s.faceCenter[1]}), faceRadius: ${s.faceRadius}, hubRadius: ${s.hubRadius}),`;
};
writeFileSync(join(root, "Cadence/Views/PlateSprites.swift"),
`// Generated by web/tools/install-plate-sprites.mjs from render-plate-sprites.py output. Do not edit.
import CoreGraphics

/// Placement metadata for the rendered loaded-bar sprites in the asset
/// catalog (PlateSprites). Mirrors web/app/js/plate-sprites.js.
enum PlateSprites {
    enum Sprite {
        case plate(family: String, shape: String, angle: String, size: CGSize, faceCenter: CGPoint, faceRadius: Double, hubRadius: Double)
        case bar(kind: String, angle: String, size: CGSize, axisStart: CGPoint, axisEnd: CGPoint, spanUnits: Double)
    }

    /// Scene units per plate radius (BarbellScene: radius = diameter × 0.18 → 81 for a 450 mm plate).
    static let unit: Double = ${manifest.unit}
    /// "<family>:<plate id>" → "<family>-<diameter>x<thickness>" shape key.
    static let plates: [String: String] = [
${Object.entries(manifest.plates).sort().map(([k, v]) => `        "${k}": "${v}",`).join("\n")}
    ]
    static let sprites: [String: Sprite] = [
${entries.map(swiftSprite).join("\n")}
    ]
}
`);
// Service worker precache: the sprite list lives between markers in app/sw.js.
const swPath = join(root, "web/app/sw.js");
let sw = readFileSync(swPath, "utf8");
const list = names.map((name) => `  "assets/plates/${name}.png",`).join("\n");
const block = `  // plate-sprites:begin (generated by tools/install-plate-sprites.mjs)\n${list}\n  // plate-sprites:end`;
sw = sw.includes("plate-sprites:begin")
  ? sw.replace(/  \/\/ plate-sprites:begin[\s\S]*?\/\/ plate-sprites:end/, block)
  : sw.replace('  "assets/plate-steel.png", "assets/plate-bumper.png",', `${block}\n  "js/plate-sprites.js",`);
writeFileSync(swPath, sw);
writeFileSync(join(webDir, "README.md"), `# Loaded-bar sprites

Rendered by \`web/tools/render-plate-sprites.py\` (a deterministic signed-distance
ray marcher with a studio light rig) and installed here and into
\`Cadence/Assets.xcassets/PlateSprites\` by \`web/tools/install-plate-sprites.mjs\`;
the two copies are byte-identical and tested. Plates are greyscale and are
colourised at runtime from the shared luminance matrix; hubs and bar parts
stay untinted. One sprite per plate shape (diameter × thickness) at each
scene angle (assembled 18°, exploded 38°), plus shaft, sleeves, and collars.
Placement metadata is generated into \`web/app/js/plate-sprites.js\` and
\`Cadence/Views/PlateSprites.swift\`. No photograph or third-party asset is
involved; regenerate rather than edit.
`);
console.log(`installed ${names.length} sprites for both clients`);
